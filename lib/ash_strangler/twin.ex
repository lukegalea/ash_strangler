defmodule AshStrangler.Twin do
  @moduledoc """
  The legacy relation, declared as an ordinary Ash resource.

  A *twin* is a private, read-only, `migrate? false` `AshPostgres` resource over
  a table this application does not own and never will. It is generated by
  `mix ash_strangler.gen.twin`, which introspects the live database — so the
  legacy schema is **read**, not retyped.

      defmodule MyApp.Legacy.Accounts do
        use Ash.Resource,
          domain: MyApp.Legacy,
          data_layer: AshPostgres.DataLayer,
          extensions: [AshStrangler.Twin]

        postgres do
          table "accounts"
          schema "legacy"
          repo MyApp.Repo
          migrate? false
        end

        attributes do
          attribute :id, :integer, primary_key?: true
          attribute :email, :string
          attribute :first_name, :string
        end

        identities do
          identity :index_accounts_on_email, [:email]
        end
      end

  ## What the twin buys, and why nothing else does

  `expr(first_name)` has to mean something. Without a resource behind it,
  `first_name` is a bare atom: `AshSql` refuses to render it and
  `Ash.Filter.hydrate_refs/2` has nothing to look it up on. Declaring the legacy
  columns *inline* inside the `strangler` block would satisfy the printer, but it
  would restate the legacy schema by hand — which is the defect the whole
  redesign is about. So the twin is a real resource, and four DSL constructs
  collapse into things Ash already has:

  | Deleted | Replaced by |
  |---|---|
  | `cast: :citext` | the twin attribute's type against the target attribute's type |
  | `index "…", unique: true, columns: [...]` | an `identity` on the twin, checked against `pg_index` by `mix ash_strangler.check` |
  | `join "legacy.addresses", as: "addr", on: "addr.account_id = accounts.id"` | a relationship on the twin; the mapping reads `expr(address.city)` |
  | `AshStrangler.Diagram.Sql`'s regex and its `known_columns:` escape hatch | typed attributes, so lineage is a fact |

  ## The twin is a snapshot, and snapshots go stale

  It is generated by introspection, so a column the legacy application's next
  migration adds is invisible until the twin is regenerated. There are two
  mitigations, and they answer different questions:

    * Pin the twin to a snapshot catalog (`AshStrangler.Snapshot`) with
      `twin do snapshot "priv/legacy/snapshot/catalog.json" end`. The catalog
      becomes an `@external_resource` of the twin, and
      `AshStrangler.Verifiers.VerifySnapshot` fails compilation, naming the
      column, whenever the twin's columns, types, nullability or primary key
      disagree with it. The catalog in turn is held to the live database by
      `mix ash_strangler.snapshot drift`.
    * Without a snapshot, `mix ash_strangler.check` diffs every twin against the
      live database. What that covers:

        * **freshness**: the twin's columns against `information_schema.columns`,
          so a column added or dropped is reported;
        * **identities**: the twin's unique sets against `pg_index`, key columns
          of whole-table, plain-column indexes only;
        * **twin columns**: for each column the twin declares, what
          `mix ash_strangler.gen.twin` would write today. A value set that grew (an
          enum label or `CHECK` value the twin's `one_of` lacks) and a coarse type
          that changed fail; a narrowed set, a `one_of` the catalog no longer
          yields, and a nullability that differs warn.

      It does not cover a column the twin leaves out beyond reporting it, a
      typmod (`varchar(20)` against `varchar(40)`), a default, a collation, or a
      change inside a `CHECK` that is not a plain `IN` list. A hand-written twin is
      held only to what it declares.

  ## Secrets

  `secrets [:password_digest]` names legacy columns that must never leave the
  legacy database through this package: they are not attributes of the twin,
  so no mapping, view, ledger image or notification can carry them. A mapping
  that names one fails to compile, and `AshStrangler.Verifiers.VerifySecrets`
  refuses a twin that declares a secret as an attribute anyway. With a
  snapshot, a secret must be a column the catalog has.

  ## Watching a relation

  `watch "channel"` asks `mix ash_strangler.gen.migration` for a notify-only
  trigger on the twin's relation: key-only payload, no ledger, no strangled
  resource required. It is for relations whose changes matter (a membership
  table, a permission table) but which no resource maps. See
  `AshStrangler.Sql.Watch`.

  ## Only the system actor reads a twin

  A twin is raw legacy data with none of the canonical resource's policies, so
  nothing but the host's own machinery (views, observers, backfills, fixture
  writers) should read it. `system_actor MyApp.Checks.SystemActor` gives the
  twin a single generated policy that authorizes that actor and nobody else:

      use Ash.Resource,
        ...,
        extensions: [AshStrangler.Twin],
        authorizers: [Ash.Policy.Authorizer]

      twin do
        system_actor MyApp.Checks.SystemActor
      end

  `authorize?: false` still reads, as it does on any resource; the policy
  closes the paths that carry an actor (an API, an admin UI, a tool call).

  ## Joins are always `LEFT`, and that is now structural rather than a default

  The old DSL let a join declare `type: :inner` and argued at length that `:left`
  had to be the default, because an `INNER JOIN` *removes rows* — a legacy row
  with no match disappears from the view, so the new application sees fewer
  records than the old one and nothing reports it. Deriving the join from a
  relationship removes the option entirely: a relationship describes which rows
  *relate*, not which rows *survive*. An author who genuinely wants to drop
  unmatched rows writes a `filter` on the read action, where it is visible as a
  filter.
  """

  @twin %Spark.Dsl.Section{
    name: :twin,
    describe: """
    What this package needs to know about the legacy relation beyond its
    columns: the snapshot it was generated from, the columns it deliberately
    leaves out, and whether its writes are announced.
    """,
    examples: [
      """
      twin do
        snapshot "priv/legacy/snapshot/catalog.json"
        secrets [:password_digest, :reset_token]
        watch "legacy_memberships"
        system_actor MyApp.Checks.SystemActor
      end
      """
    ],
    schema: [
      snapshot: [
        type: :string,
        doc: """
        Path, relative to the project root, of the `catalog.json` this twin was
        generated from. It becomes an `@external_resource`, and
        `AshStrangler.Verifiers.VerifySnapshot` fails compilation when the twin
        and the catalog disagree.
        """
      ],
      secrets: [
        type: {:list, :atom},
        default: [],
        doc: """
        Legacy column names this twin must never carry. They are not
        attributes, so no mapping, view, ledger image or notification can read
        them; a mapping that names one fails to compile.
        """
      ],
      watch: [
        type: :string,
        doc: """
        A `pg_notify` channel. When set, `mix ash_strangler.gen.migration`
        emits a notify-only trigger on this relation whose payload is the
        relation, the operation and the primary key, and nothing else.
        """
      ],
      system_actor: [
        type: {:or, [:atom, {:tuple, [:atom, :keyword_list]}]},
        doc: """
        A policy check (an `Ash.Policy.Check` module, or `{module, opts}`)
        that matches the host's system actor. The twin then gets one policy,
        `policy always() do authorize_if <check> end`, so an actor that is not
        the system actor reads no legacy rows through it. Needs
        `authorizers: [Ash.Policy.Authorizer]` on the twin; a `bypass` on it
        is refused.
        """
      ]
    ]
  }

  use Spark.Dsl.Extension,
    sections: [@twin],
    transformers: [
      AshStrangler.Transformers.DeclareSnapshotResource,
      AshStrangler.Transformers.AddTwinPolicy
    ],
    verifiers: [
      AshStrangler.Verifiers.VerifySecrets,
      AshStrangler.Verifiers.VerifySnapshot,
      AshStrangler.Verifiers.VerifyWatch
    ]

  @doc "The snapshot catalog path the twin is pinned to, or `nil`."
  @spec snapshot(Ash.Resource.t() | Spark.Dsl.t()) :: String.t() | nil
  def snapshot(twin), do: Spark.Dsl.Extension.get_opt(twin, [:twin], :snapshot, nil)

  @doc "The legacy column names the twin declares secret, as strings."
  @spec secrets(Ash.Resource.t() | Spark.Dsl.t()) :: [String.t()]
  def secrets(twin) do
    twin |> Spark.Dsl.Extension.get_opt([:twin], :secrets, []) |> Enum.map(&to_string/1)
  end

  @doc "The channel a watched twin notifies on, or `nil` when it is not watched."
  @spec watch(Ash.Resource.t() | Spark.Dsl.t()) :: String.t() | nil
  def watch(twin), do: Spark.Dsl.Extension.get_opt(twin, [:twin], :watch, nil)

  @doc "The policy check that matches the host's system actor, or `nil`."
  @spec system_actor(Ash.Resource.t() | Spark.Dsl.t()) :: module() | {module(), keyword()} | nil
  def system_actor(twin), do: Spark.Dsl.Extension.get_opt(twin, [:twin], :system_actor, nil)

  @doc """
  True when `module` is usable as a twin: a compiled `AshPostgres` resource with a
  table.

  Deliberately not "has the `AshStrangler.Twin` extension". The extension is
  documentation and a marker; a hand-written `AshPostgres` resource over a legacy
  table works identically, and refusing it would be gatekeeping with no
  mechanism behind it.
  """
  @spec twin?(term()) :: boolean()
  def twin?(module) when is_atom(module) do
    Code.ensure_loaded?(module) and
      function_exported?(module, :spark_dsl_config, 0) and
      Ash.Resource.Info.resource?(module) and
      not is_nil(AshPostgres.DataLayer.Info.table(module))
  end

  def twin?(_other), do: false

  @doc """
  The twin's relation, schema-qualified: `"legacy.users"`.

  Unqualified when the twin declares no schema, which relies on `search_path`
  exactly as much as a `postgres do table "users" end` with no schema already
  does.
  """
  @spec relation(Ash.Resource.t()) :: String.t()
  def relation(twin) do
    table = table!(twin)

    case AshPostgres.DataLayer.Info.schema(twin) do
      nil -> table
      schema -> "#{schema}.#{table}"
    end
  end

  @doc """
  The twin's schema and table, each as the twin declares it: `{"legacy", "users"}`, or
  `{nil, "users"}` when the twin declares no schema.

  Read from the twin's `postgres` block, not from `relation/1`'s string, because a schema or
  table whose name contains a dot (`"odd.schema"`) cannot be found again by splitting the
  logical name. Anything that needs the parts of a twin's relation asks here.
  """
  @spec schema_and_table(Ash.Resource.t()) :: {String.t() | nil, String.t()}
  def schema_and_table(twin), do: {AshPostgres.DataLayer.Info.schema(twin), table!(twin)}

  @doc """
  The twin's relation as SQL spells it: each part through the printer's identifier
  rule, so `legacy."Mixed_Items"`.

  `relation/1` is the relation's logical name -- what a report prints and what a
  derived key hashes -- and stays as it is. Every statement that *names* the
  relation (a `FROM`, an `INSERT INTO`, a `CREATE INDEX ... ON`) spells it here,
  because PostgreSQL folds an unquoted `Mixed_Items` to `mixed_items`. A lowercase
  name stays bare, so the SQL for the common case is unchanged.
  """
  @spec sql_relation(Ash.Resource.t()) :: String.t()
  def sql_relation(twin) do
    table = twin |> table!() |> AshStrangler.Sql.Printer.identifier()

    case AshPostgres.DataLayer.Info.schema(twin) do
      nil -> table
      schema -> "#{AshStrangler.Sql.Printer.identifier(schema)}.#{table}"
    end
  end

  @doc "The twin's bare table name, which is also the default alias for it."
  @spec table!(Ash.Resource.t()) :: String.t()
  def table!(twin) do
    AshPostgres.DataLayer.Info.table(twin) ||
      raise ArgumentError,
            "#{inspect(twin)} is used as a strangler `source` but has no `postgres do table \"...\" end`"
  end

  @doc """
  The real column name behind an attribute.

  Ash's `source:` option is the mapping from attribute name to column name, so a
  twin whose generator found a column Elixir would not want as an atom — `"Type"`,
  `"order"` — carries it there and this reads it.
  """
  @spec column!(Ash.Resource.t(), atom()) :: String.t()
  def column!(twin, attribute) do
    case Ash.Resource.Info.attribute(twin, attribute) do
      nil ->
        raise ArgumentError, unknown_attribute_message(twin, attribute)

      %{source: source} when not is_nil(source) ->
        to_string(source)

      %{name: name} ->
        to_string(name)
    end
  end

  @doc "The Ash type of a twin attribute, for deriving casts and checking type agreement."
  @spec type!(Ash.Resource.t(), atom()) :: Ash.Type.t()
  def type!(twin, attribute) do
    case Ash.Resource.Info.attribute(twin, attribute) do
      nil -> raise ArgumentError, unknown_attribute_message(twin, attribute)
      %{type: type} -> type
    end
  end

  @doc "Every attribute name the twin declares."
  @spec columns(Ash.Resource.t()) :: [atom()]
  def columns(twin), do: twin |> Ash.Resource.Info.attributes() |> Enum.map(& &1.name)

  @doc """
  The sets of columns the twin declares unique, as `MapSet`s of column-name
  strings.

  This is what `AshStrangler.Verifiers.VerifyIdentitiesBacked` compares an Ash
  identity against, and what `mix ash_strangler.check` compares `pg_index`
  against.
  """
  @spec unique_column_sets(Ash.Resource.t()) :: MapSet.t(MapSet.t(String.t()))
  def unique_column_sets(twin) do
    identities = Ash.Resource.Info.identities(twin)
    primary_key = Ash.Resource.Info.primary_key(twin)

    sets =
      for identity <- identities,
          into: MapSet.new(),
          do: MapSet.new(identity.keys, &column!(twin, &1))

    if primary_key == [] do
      sets
    else
      MapSet.put(sets, MapSet.new(primary_key, &column!(twin, &1)))
    end
  end

  @doc """
  Resolves a relationship path into the joins needed to reach it.

  Returns `{:ok, [join]}` where each join is
  `%{relation:, sql_relation:, alias:, on:, relationship:}` in the order they must
  appear in the `FROM` clause, or `{:error, message}` when a step of the path is not a
  relationship on the twin. `relation:` is the logical name (`relation/1`, what lineage
  and a report name the relation by); `sql_relation:` and the columns in `on:` are
  spelled for SQL.

  Only `belongs_to` and `has_one` are resolvable. A `has_many` or `many_to_many`
  would multiply rows — one legacy account with three addresses becoming three
  view rows, and therefore three `Customer` records where the old application had
  one. That is the fan-out failure the tool exists to refuse, so it is refused
  here by name rather than measured later.
  """
  @spec joins_for(Ash.Resource.t(), [atom()]) ::
          {:ok,
           [
             %{
               relation: String.t(),
               sql_relation: String.t(),
               alias: String.t(),
               on: String.t(),
               relationship: term()
             }
           ]}
          | {:error, String.t()}
  def joins_for(twin, path) do
    path
    |> Enum.reduce_while({:ok, {twin, table!(twin), []}}, fn step, {:ok, {current, alias, acc}} ->
      case Ash.Resource.Info.relationship(current, step) do
        nil ->
          {:halt,
           {:error,
            "#{inspect(current)} has no relationship #{inspect(step)}. " <>
              "A mapping that reads `expr(#{Enum.join(path, ".")})` needs one, and it must be a " <>
              "`belongs_to` or `has_one`."}}

        %{cardinality: :many} = relationship ->
          {:halt,
           {:error,
            "relationship #{inspect(step)} on #{inspect(current)} is a #{relationship.type}, which " <>
              "returns many rows. Joining it would multiply view rows — one legacy row becoming " <>
              "three — so the new application would report more records than the old one. Read it " <>
              "through its own resource instead."}}

        relationship ->
          destination = relationship.destination
          step_alias = to_string(step)

          join = %{
            relation: relation(destination),
            sql_relation: sql_relation(destination),
            alias: step_alias,
            on:
              "#{step_alias}.#{AshStrangler.Sql.Printer.column(destination, relationship.destination_attribute)} = " <>
                "#{alias}.#{AshStrangler.Sql.Printer.column(current, relationship.source_attribute)}",
            relationship: relationship
          }

          {:cont, {:ok, {destination, step_alias, acc ++ [join]}}}
      end
    end)
    |> case do
      {:ok, {_resource, _alias, joins}} -> {:ok, joins}
      {:error, message} -> {:error, message}
    end
  end

  @doc """
  The resource a relationship path lands on, for resolving the attribute at the
  end of it.
  """
  @spec resource_at(Ash.Resource.t(), [atom()]) :: {:ok, Ash.Resource.t()} | {:error, String.t()}
  def resource_at(twin, []), do: {:ok, twin}

  def resource_at(twin, [step | rest]) do
    case Ash.Resource.Info.relationship(twin, step) do
      nil -> {:error, "#{inspect(twin)} has no relationship #{inspect(step)}"}
      relationship -> resource_at(relationship.destination, rest)
    end
  end

  defp unknown_attribute_message(twin, attribute) do
    known = twin |> columns() |> Enum.sort() |> Enum.map_join(", ", &inspect/1)

    """
    #{inspect(twin)} has no attribute #{inspect(attribute)}.

    It declares: #{known}

    If the legacy table really has that column, the twin is stale — regenerate it:

        mix ash_strangler.gen.twin #{inspect(twin)}
    """
  end
end
