defmodule Mix.Tasks.AshStrangler.Gen.EventsBridge do
  @shortdoc "Generates the companion read-only resource over strangler_observations"

  @moduledoc """
  Renders `<Namespace>.StranglerObservations`: a companion READ-ONLY Ash
  resource over `strangler_observations` that the host mounts beside its
  event log for a unified timeline.

      mix ash_strangler.gen.events_bridge MyApp.Clm --repo MyApp.Repo

  The bridge has no create/update/destroy -- observations are never
  replayable as actions, and an action event ("Luke ran `Contract.archive`")
  stays distinct from an observation ("the shared row's `archived` changed in
  legacy"). `mapping_version` travels on every row so a consumer can tell a
  value change from a meaning change.
  """

  use Mix.Task

  @requirements ["app.config"]

  @impl Mix.Task
  def run(args) do
    {opts, args} = OptionParser.parse!(args, strict: [repo: :string])

    namespace =
      case args do
        [namespace] -> namespace
        _ -> Mix.raise("usage: mix ash_strangler.gen.events_bridge <Namespace> --repo <Repo>")
      end

    repo =
      Keyword.get(opts, :repo) ||
        Mix.raise("--repo is required: the bridge reads the host's schema")

    repo_module = Module.concat([repo])
    module = Module.concat([namespace, "StranglerObservations"])

    Mix.shell().info(render(module, repo_module))
  end

  defp render(module, repo) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      Companion read-only resource over `strangler_observations`, generated by
      `mix ash_strangler.gen.events_bridge`.

      Mount it beside the host's event log for a unified timeline. It has no
      create/update/destroy: observations are NEVER replayable as actions, and
      they stay a different KIND of record from action events -- "the shared
      row changed in legacy" versus "the host ran a command".

      Distinct fields worth reading before joining on anything:
        * `source_event_id` -- the ledger's bigserial id, the dedup key
          (at-least-once delivery; id order is NOT commit order).
        * `category` -- `baseline` is "seen as executed", never "happened now".
        * `mapping_version` -- a value change under a changed version is a
          MEANING change; re-baseline instead of diffing.
        * `invalidated_attributes` -- joined reads the event unmoored; there
          is deliberately no "after" for those.
      \"\"\"

      use Ash.Resource,
        domain: nil,
        data_layer: AshPostgres.DataLayer

      postgres do
        table "strangler_observations"
        schema "public"
        repo #{inspect(repo)}
        migrate? false
      end

      attributes do
        uuid_primary_key :id

        attribute :source_event_id, :integer, public?: true
        attribute :baseline_group, :uuid, public?: true
        attribute :category, :atom do
          public? true
          constraints one_of: [:baseline, :observation]
        end
        attribute :resource, :string, public?: true
        attribute :record_id, :string, public?: true
        attribute :operation, :atom, public?: true
        attribute :before, :map, public?: true
        attribute :after, :map, public?: true
        attribute :changed_attributes, :map, public?: true
        attribute :invalidated_attributes, :map, public?: true
        attribute :origin, :atom, public?: true
        attribute :attribution, :map, public?: true
        attribute :correlation_id, :string, public?: true
        attribute :causation_id, :string, public?: true
        attribute :mapping_version, :string, public?: true
        attribute :source, :map, public?: true
        attribute :captured_at, :utc_datetime_usec, public?: true
        attribute :recorded_at, :utc_datetime_usec, public?: true
      end

      code_interface do
        define :by_id, get?: true, args: [:id]
        define :timeline, action: :read
      end

      actions do
        defaults [:read]

        read :by_id do
          get_by :id
        end

        # Replay refusal is structural: no create/update/destroy exists, so
        # there is no action path to replay observations through.
      end
    end
    """
  end
end
