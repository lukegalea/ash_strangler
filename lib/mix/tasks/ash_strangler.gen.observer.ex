defmodule Mix.Tasks.AshStrangler.Gen.Observer do
  @shortdoc "Generates the Oban worker that drains observations for a resource"

  @moduledoc """
  Renders the host-side Oban worker around
  `AshStrangler.Observation.Processor.drain/4` — the observation mode's
  counterpart to `mix ash_strangler.gen.ingester`.

      mix ash_strangler.gen.observer MyApp.Clm.Contract MyApp.Repo

  The worker claims the resource's unprocessed ledger events `FOR UPDATE
  SKIP LOCKED` WITHOUT marking them processed (the materialisation ingester
  owns that column), projects each into `strangler_observations` idempotently,
  and runs the resource's declared `observers` with their receipts in the
  same transaction. The delivery contract lives on `AshStrangler.Observer`;
  the worker is only the clock.

  Enqueue it on a cron beside the wake listener — same story as the ingester:
  a missed wake costs delay, not delivery.
  """

  use Mix.Task

  @requirements ["app.config"]

  @impl Mix.Task
  def run(args) do
    case OptionParser.parse!(args, strict: []) do
      {[resource, repo], _} ->
        module = Module.concat([resource])
        repo_module = Module.concat([repo])

        if not Code.ensure_loaded?(module) or not function_exported?(module, :spark_dsl_config, 0) do
          Mix.raise("#{resource} is not a compiled Ash resource")
        end

        observers = AshStrangler.Info.observers(module)

        if observers == [] do
          Mix.shell().info("""
          warning: #{resource} declares no `observers:` -- the worker will project
          observations into the store and deliver nothing. Declare them in the
          resource's source block:

              source ... do
                observers: [MyApp.MyObserver]
              end
          """)
        end

        Mix.shell().info(render(module, repo_module, observers))

      _ ->
        Mix.raise("usage: mix ash_strangler.gen.observer <Resource> <Repo>")
    end
  end

  defp render(resource, repo, observers) do
    worker = worker_name(resource)

    """
    defmodule #{inspect(worker)} do
      @moduledoc \"\"\"
      Drains observations for #{inspect(resource)}, generated by
      `mix ash_strangler.gen.observer`.

      Delivery contract: `AshStrangler.Observer` (at-least-once by
      `source_event_id`, never exactly-once, ledger id order is NOT commit
      order). The receipts make replay safe; nothing here marks events
      processed -- the materialisation ingester owns that column.

          config :my_app, Oban,
            queues: [ash_strangler_observation: 10],
            plugins: [
              {Oban.Plugins.Cron,
               entries: [%{cron: "*/1 * * * *", job: #{inspect(worker)}}]}
            ]
      \"\"\"

      use Oban.Worker, queue: :ash_strangler_observation, max_attempts: 10, unique: [period: 30]

      alias #{inspect(repo)}

      @batch_size 100
      @observers #{inspect(observers)}

      @impl Oban.Worker
      def perform(_job), do: drain()

      @doc \"\"\"
      Drains until this resource's backlog is empty, returning
      `{:ok, total_observed}`.
      \"\"\"
      def drain(acc \\\\ 0) do
        case drain_batch() do
          {:ok, 0} -> {:ok, acc}
          {:ok, count} -> drain(acc + count)
          {:error, reason} -> {:error, reason}
        end
      end

      # The claim holds the row locks until the batch commits, so concurrent
      # workers claim disjoint rows. The events stay unprocessed -- the
      # observation store's partial unique index and the receipts carry
      # idempotence instead, which is what makes replay safe.
      defp drain_batch do
        case #{inspect(repo)}.transaction(fn ->
               AshStrangler.Observation.Processor.drain(
                 #{inspect(repo)},
                 #{inspect(resource)},
                 @observers,
                 batch: @batch_size
               )
             end) do
          {:ok, count} -> {:ok, count}
          {:error, reason} -> {:error, reason}
        end
      end
    end
    """
  end

  defp worker_name(resource) do
    resource
    |> Module.split()
    |> then(&(&1 ++ ["ObservationWorker"]))
    |> Module.concat()
  end
end
